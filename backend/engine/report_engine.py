from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
import datetime
import os

class TrustBuyReport:
    def __init__(self, product_name, trust_score, price_status, flagged_count):
        self.product_name = product_name
        self.trust_score = trust_score
        self.price_status = price_status
        self.flagged_count = flagged_count
        
        # Ensure reports directory exists
        os.makedirs("reports", exist_ok=True)
        self.filename = f"reports/TrustBuy_Audit_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"

    def generate(self) -> str:
        c = canvas.Canvas(self.filename, pagesize=letter)
        width, height = letter

        # --- Header & Branding ---
        c.setFillColor(colors.black)
        c.rect(0, height - 80, width, 80, fill=1)
        c.setFillColor(colors.white)
        c.setFont("Helvetica-Bold", 24)
        c.drawString(40, height - 50, "TRUSTBUY™ AUDIT REPORT")
        
        # --- Summary Section ---
        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 14)
        c.drawString(40, height - 120, f"Product: {self.product_name}")
        c.setFont("Helvetica", 12)
        c.drawString(40, height - 140, f"Generated on: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

        # --- The Trust Score (Visual) ---
        score_color = colors.green if float(self.trust_score) > 70 else colors.red
        c.setFillColor(score_color)
        c.setFont("Helvetica-Bold", 40)
        c.drawString(40, height - 200, f"{self.trust_score}%")
        c.setFont("Helvetica", 12)
        c.setFillColor(colors.black)
        c.drawString(160, height - 190, "Global Trust Index")

        # --- Key Findings ---
        c.setStrokeColor(colors.lightgrey)
        c.line(40, height - 230, width - 40, height - 230)
        
        c.setFont("Helvetica-Bold", 12)
        c.drawString(40, height - 260, "RISK ASSESSMENT:")
        
        findings = [
            f"• Flagged Reviews: {self.flagged_count}",
            f"• Price Integrity: {self.price_status}",
            f"• Detection Method: Hybrid Linguistic & Behavioral Engine",
            f"• Security Verification: SECURE (API Checked)",
            f"• Currency Normalized: USD Base"
        ]
        
        y_pos = height - 280
        for item in findings:
            c.drawString(50, y_pos, item)
            y_pos -= 20

        # --- Footer ---
        c.setFont("Helvetica-Oblique", 8)
        c.drawString(40, 40, "Confidential: Generated by TrustBuy AI Engine. Data based on real-time e-commerce scraping.")
        
        c.save()
        return self.filename
